from __future__ import annotations

import random
from .schemas import Application, Criticality, Dependency, IntegrationType, Portfolio, Sensitivity

DOMAINS = [
    "Customer",
    "Identity",
    "Payments",
    "Billing",
    "CRM",
    "ERP",
    "Warehouse",
    "Finance",
    "Analytics",
    "Reporting",
    "Documents",
    "Notifications",
    "Legacy Integration",
    "Mainframe Gateway",
]
LANGUAGES = [
    ("Java", "Spring", "17"),
    ("Python", "FastAPI", "3.12"),
    ("C#", ".NET", "8"),
    ("Java", "Struts", "8"),
    ("COBOL", "CICS", "legacy"),
]
DBS = [
    "postgres-customer",
    "postgres-orders",
    "oracle-core",
    "sqlserver-finance",
    "mysql-shared",
    None,
]


def generate_portfolio(size: int = 100, seed: int = 42) -> Portfolio:
    if size < 3 or size > 5000:
        raise ValueError("size must be between 3 and 5000")
    rng = random.Random(seed)
    apps: list[Application] = []
    for i in range(size):
        language, framework, version = rng.choice(LANGUAGES)
        legacy = framework in {"Struts", "CICS"}
        criticality = rng.choices(list(Criticality), weights=[2, 5, 3, 1])[0]
        db = rng.choice(DBS)
        apps.append(
            Application(
                application_id=f"app-{i:04d}",
                name=f"{rng.choice(DOMAINS)} Service {i:04d}",
                description="Synthetic demonstration workload generated by CloudMorph.",
                business_domain=rng.choice(DOMAINS),
                owner=f"Team-{rng.randint(1, max(2, size // 20))}",
                business_criticality=criticality,
                business_value=round(rng.uniform(2, 10), 2),
                change_frequency=round(rng.uniform(1, 10), 2),
                runtime="jvm" if language == "Java" else language.lower(),
                language=language,
                framework=framework,
                runtime_version=version,
                database=db,
                database_size_gb=round(rng.uniform(1, 1500), 2),
                deployment_model="vm" if legacy or rng.random() < 0.55 else "container",
                operating_system="rhel7" if legacy else "linux",
                traffic_rps=round(rng.uniform(1, 1500), 2),
                peak_traffic_rps=round(rng.uniform(1500, 4000), 2),
                availability_requirement=rng.choice([99.0, 99.5, 99.9, 99.95, 99.99]),
                rto_hours=rng.choice([0.5, 1, 2, 4, 8, 24]),
                rpo_hours=rng.choice([0.25, 1, 4, 12, 24]),
                data_sensitivity=rng.choice(list(Sensitivity)),
                regulatory_tags=rng.sample(["PCI", "SOX", "PII"], k=rng.randint(0, 2)),
                estimated_current_cost=round(rng.uniform(500, 15000), 2),
                technical_debt_score=round(rng.uniform(6, 10) if legacy else rng.uniform(1, 8), 2),
                team_skill_level=round(rng.uniform(2, 9), 2),
                test_coverage=round(rng.uniform(5, 90), 2),
                deployment_frequency=round(rng.uniform(0.1, 30), 2),
                incident_frequency=round(rng.uniform(0, 10), 2),
                scalability_requirement=round(rng.uniform(1, 10), 2),
                observability_maturity=round(rng.uniform(1, 9), 2),
                identity_maturity=round(rng.uniform(1, 9), 2),
                migration_effort=round(rng.uniform(1, 12), 2),
                migration_risk=round(rng.uniform(1, 9), 2),
                migration_cost=round(rng.uniform(3000, 60000), 2),
                usage_level=round(rng.uniform(1, 10), 2),
                commodity_fit=round(rng.uniform(1, 10), 2),
                redundancy_score=round(rng.uniform(0, 10), 2),
                replacement_fit=round(rng.uniform(1, 10), 2),
                residency_region=rng.choice([None, None, "IN", "EU"]),
                maintenance_tag=rng.choice([None, "weekend", "night"]),
                synthetic=True,
            )
        )
    # Backbone dependency chain prevents a graph of isolated random nodes.
    for i in range(1, size):
        if rng.random() < 0.72:
            target = max(0, i - rng.randint(1, min(i, 8)))
            apps[i].dependencies.append(
                Dependency(
                    target=apps[target].application_id,
                    integration_type=rng.choice(list(IntegrationType)),
                    synchronous=rng.random() < 0.7,
                )
            )
    # Fan-in/fan-out hubs and additional sparse integrations.
    hubs = [0, min(2, size - 1), min(7, size - 1)]
    for i in range(size):
        if i not in hubs and rng.random() < 0.28:
            target = rng.choice(hubs)
            if target != i and all(
                d.target != apps[target].application_id for d in apps[i].dependencies
            ):
                apps[i].dependencies.append(
                    Dependency(
                        target=apps[target].application_id, integration_type=IntegrationType.api
                    )
                )
        if rng.random() < 0.22:
            target = rng.randrange(size)
            if target != i and all(
                d.target != apps[target].application_id for d in apps[i].dependencies
            ):
                apps[i].dependencies.append(
                    Dependency(
                        target=apps[target].application_id,
                        integration_type=rng.choice(list(IntegrationType)),
                    )
                )
    # Intentional 3-node SCC when size allows.
    if size >= 6:
        cyc = [size - 3, size - 2, size - 1]
        for source, target in zip(cyc, cyc[1:] + cyc[:1]):
            tid = apps[target].application_id
            if all(d.target != tid for d in apps[source].dependencies):
                apps[source].dependencies.append(
                    Dependency(target=tid, integration_type=IntegrationType.legacy)
                )
    for app in apps:
        app.integration_count = len(app.dependencies)
        app.peak_traffic_rps = max(app.peak_traffic_rps, app.traffic_rps)
    return Portfolio(name=f"Synthetic Enterprise {size}", applications=apps, synthetic=True)
