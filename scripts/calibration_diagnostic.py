from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from app.assessment import assess_portfolio
from app.generator import generate_portfolio

ROOT = Path(__file__).resolve().parents[1]
counts = Counter()
per_seed = []
for seed in (11, 23, 42, 77, 101):
    portfolio = generate_portfolio(100, seed=seed)
    c = Counter(row["recommendation"] for row in assess_portfolio(portfolio))
    counts.update(c)
    per_seed.append({"seed": seed, "distribution": dict(c)})
total = sum(counts.values())
shares = {k: round(v / total, 4) for k, v in sorted(counts.items())}
warning = None
winner, share = max(shares.items(), key=lambda kv: kv[1])
if share >= 0.85:
    warning = f"{winner} selected for {share:.1%} across heterogeneous synthetic portfolios; review calibration."
out = {
    "sample_applications": total,
    "seeds": [11, 23, 42, 77, 101],
    "distribution": dict(counts),
    "shares": shares,
    "warning": warning,
    "note": "Diagnostic only; no target distribution is enforced. Synthetic portfolios are generated by CloudMorph.",
}
(ROOT / "benchmarks" / "recommendation_distribution.json").write_text(
    json.dumps(out, indent=2), encoding="utf-8"
)
print(json.dumps(out, indent=2))
